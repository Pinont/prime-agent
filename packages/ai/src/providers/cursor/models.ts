/**
 * Total request cost for a bundled Cursor model, ported from omp
 * `calculateUsageCost` (`packages/catalog/src/models.ts`): rates are
 * $/M tokens, so each component is `rate × tokens / 1_000_000`, and the total
 * is the sum. The omp original additionally handles time-based pricing,
 * long-context thresholds and Anthropic `cttl` breakdowns; bundled Cursor
 * rates are flat, so those arms reduce to this core calculation.
 */
export function cursorCostFor(
	model: { cost: CursorBundledCost },
	usage: { input: number; output: number; cacheRead: number; cacheWrite: number },
): number {
	const rates = model.cost;
	const input = (rates.input / 1_000_000) * usage.input;
	const output = (rates.output / 1_000_000) * usage.output;
	const cacheRead = (rates.cacheRead / 1_000_000) * usage.cacheRead;
	const cacheWrite = (rates.cacheWrite / 1_000_000) * usage.cacheWrite;
	return input + output + cacheRead + cacheWrite;
}
