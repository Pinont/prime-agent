/**
 * Bundled Cursor model catalog and cost calculation — a curated pure
 * TypeScript subset of the oh-my-pi `packages/catalog/src/models.json`
 * "cursor" section (119 rows there; 40 here). Each entry maps the omp row's
 * `effortRouting` into a prime-agent {@link ThinkingLevelMap} (pi thinking
 * level → Cursor wire model id; `null` marks the level unsupported):
 *
 * - `off` → the routing `off` target when present, else `null` for
 *   `requiresEffort` families, else `requestModelId ?? id`.
 * - each supported effort → its routing target when present, else the
 *   family's fallback wire id (`requestModelId ?? id`, mirroring omp
 *   `resolveWireModelId`), else `null`.
 *
 * Rows without a thinking surface map to `{ off: <id>, …: null }` — the id
 * itself is the thinking-off wire id.
 */

import type { ThinkingLevelMap } from "../../types.js";

/** Flat $/M-token rates for a bundled Cursor model. */
export interface CursorBundledCost {
	input: number;
	output: number;
	cacheRead: number;
	cacheWrite: number;
}

/** A curated bundled Cursor model (subset of omp models.json "cursor"). */
export interface CursorBundledModel {
	id: string;
	name: string;
	reasoning: boolean;
	/**
	 * Pi thinking level → Cursor wire model id. Missing-unlike-null: every
	 * level is present; `null` marks the level as unsupported.
	 */
	thinkingLevelMap: ThinkingLevelMap;
	input: ("text" | "image")[];
	cost: CursorBundledCost;
	contextWindow: number;
	maxTokens: number;
	/** Flagship model surfaced above non-featured models in pickers. */
	featured?: boolean;
	/** Additional selector ids that route to this model. */
	aliases?: string[];
}

